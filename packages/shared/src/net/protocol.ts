/**
 * Бинарный протокол обмена между клиентом и боевой комнатой.
 *
 * Бой гоняется поверх WebSocket-канала Colyseus, но состояния/входы мы
 * кодируем собственным компактным бинарным форматом (а не schema-Codegen),
 * чтобы ужать снапшоты на 60/20 Гц до десятков байт на кадр.
 *
 * Соглашение: первым байтом любого сообщения идёт opcode (см. ниже).
 * Последующие байты зависят от opcode и описаны в самом коде пакирования
 * (pack.ts — появится на этапе 4 вместе с FightRoom).
 */

/** Версия протокола; клиент и сервер обязаны совпадать, иначе отказ в комнате. */
export const PROTO_VERSION = 1;

// NOTE: обычные enum (НЕ const) — esbuild/rolldown не умеют const-enum через
// границы модулей, а у нас каждая кодировка поедет cross-package.

export enum Opcode {
  /** Локальный пинг-зонд (клиент -> сервер), echo-payload: клиентское время. */
  Ping = 0x01,

  /** Ответ сервера, payload: серверное время (мс). */
  Pong = 0x02,

  /** Приветствие комнаты: { sessionId, version, serverTime }. */
  Welcome = 0x10,

  /** Фрейм ввода игрока (2 байта слова + seq). Только во время боя. */
  InputFrame = 0x20,

  /** Полный снапшот раунда от сервера (2 бойца). 20 Гц. */
  Snapshot = 0x30,

  /** Событие смены фазы раунда: READY / FIGHT / KO / ROUND_END / MATCH_END. */
  RoundEvent = 0x31,

  /** Итог матча + дельты рейтинга. */
  MatchResult = 0x32,

  /** Сторона клиента (0|1) — номер бойца в снапшоте. Шлётся с каждым снапшотом. */
  Side = 0x33,

  /** Статус соперника/сервера: реконнект-таймер, DQ, пауза. */
  OpponentStatus = 0x40,
}

/** Состояние heartbeat-комнаты теперь в state.ts (Schema). */

/** Текущее мета-состояние боевой комнаты (для власти над этапом 4). */
export interface FightRoomMeta {
  name: string;
  phase: string;
  seed: number;
  createdAt: number;
}