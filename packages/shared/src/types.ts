/**
 * Общие константы симуляции и боевого тайминга.
 *
 * Эти значения живут в `shared`, потому что ОБЕ стороны (клиентское
 * предсказание + авторитетный сервер) обязаны использовать абсолютно
 * одинаковые геймплейные константы: малейшее расхождение ломает
 * детерминизм симуляции и раскатывает каждый кадр в rollback-движке.
 */

/** Фиксированный шаг симуляции (кадров в секунду). */
export const SIM_HZ = 60;
/** Длительность одного симуляционного тика, секунды. */
export const FIXED_DT = 1 / SIM_HZ;

/** Частота отправки состояний сервером (снапшотов). */
export const SNAPSHOT_HZ = 20;
/** Частота отправки входов клиентом (совпадает с шагом симуляции). */
export const INPUT_HZ = 60;

/** Матч до двух побед в раундах (bo3). */
export const ROUNDS_TO_WIN = 2;
/** Таймер раунда, секунды. */
export const ROUND_TIMER_S = 99;
/** Окно на возврат после обрыва соединения, мс. */
export const RECONNECT_GRACE_MS = 30_000;

/** Размер арены (ширина по горизонтали), px. */
export const ARENA_W = 2400;
/** Координата пола по вертикали, px. */
export const GROUND_Y = 720;

/** Количество игроков в матче (только 1v1). */
export const MAX_PLAYERS = 2;

/** Сторона бойца (индекс в массиве бойцов). */
export type Side = 0 | 1;

/** Метасостояние матча (видно клиенту и серверу одинаково). */
export type MatchPhase =
  | 'Lobby'
  | 'Countdown'
  | 'Fight'
  | 'RoundEnd'
  | 'MatchEnd'
  | 'Paused';